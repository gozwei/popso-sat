template <size_t N>
std::string bytes(const unsigned char (&a)[N]) {
  return std::string(reinterpret_cast<const char*>(a), N);
}

// The payload generators, mirroring the Python ones used for the vectors.
std::string small_text() {
  std::string s = "c small CNF for the xz tests\np cnf 20 40\n";
  for (int i = 0; i < 40; ++i) {
    s += std::to_string(i % 20 + 1) + " -" + std::to_string((i * 7) % 20 + 1) + " " +
         std::to_string((i * 3 + 5) % 20 + 1) + " 0\n";
  }
  return s;
}

// CNF-like lines: mostly "-v v+1 0" (consecutive variables, as in ladder encodings), every eighth
// line or so with pseudo-random literals from a 31-bit LCG.
std::string lcg_text(int lines, uint64_t seed) {
  uint64_t x = seed;
  std::string s;
  for (int i = 0; i < lines; ++i) {
    x = (x * 1103515245 + 12345) & 0x7FFFFFFF;
    const int v = i + 1;
    if (x % 8 == 0) {
      s += std::to_string(v) + " -" + std::to_string((x >> 8) % 5000 + 1) + " " + std::to_string((x >> 3) % 977 + 1) +
           " 0\n";
    } else {
      s += "-" + std::to_string(v) + " " + std::to_string(v + 1) + " 0\n";
    }
  }
  return s;
}

// 2.4 MB: sections of 6000 lines, every third one a verbatim copy of an earlier, far-away section
// (long matches across LZMA2 chunks, distances up to about 1.6 MB).
std::string big_payload() {
  std::vector<std::string> secs;
  size_t total = 0;
  for (uint64_t k = 0; total < 2400000; ++k) {
    std::string s = k % 3 == 2 ? secs[k / 3] : lcg_text(6000, 1000 + k);
    total += s.size();
    secs.push_back(std::move(s));
  }
  std::string all;
  for (const std::string& s : secs) all += s;
  return all;
}

// Incompressible bytes: the top byte of a 64-bit LCG.
std::string noise(size_t n, uint64_t seed) {
  uint64_t x = seed;
  std::string s;
  for (size_t i = 0; i < n; ++i) {
    x = x * 6364136223846793005ull + 1442695040888963407ull;
    s += static_cast<char>(x >> 56);
  }
  return s;
}

std::string sha_text(size_t n) {
  std::string s;
  for (int i = 0; i < 20; ++i) s += "abcdefghij";
  return s.substr(0, n);
}

