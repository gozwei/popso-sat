TEST(xz_corrupt_header_fields) {
  const std::string p6 = bytes(k_preset6);
  REQUIRE(!throws_xz(p6));
  std::string s;
  // Stream header: CRC32, check type, reserved flags.
  s = p6;
  s[7] = 1;
  CHECK(error_has(s, "stream header CRC32"));
  s[7] = 2;
  CHECK(error_has(fix_stream_header(s), "unsupported integrity check type 2"));
  s = p6;
  s[6] = 1;
  CHECK(error_has(fix_stream_header(s), "unsupported stream flags"));
  // Block header (12 bytes at offset 12: size, flags, filter 0x21, properties size 1, dictionary
  // byte, padding, CRC32).
  s = p6;
  s[16] = 23;
  CHECK(error_has(s, "block header CRC32"));
  s[16] = 41;
  CHECK(error_has(fix_block_header(s), "invalid LZMA2 dictionary size"));
  s = p6;
  s[13] = 0x04;
  CHECK(error_has(fix_block_header(s), "reserved block header flags"));
  s = p6;
  s[13] = 0x01;  // two filters: LZMA2 and a "filter 0" read from the padding
  CHECK(error_has(fix_block_header(s), "unsupported xz filter 0x0"));
  s = p6;
  s[14] = 0x04;
  CHECK(error_has(fix_block_header(s), "BCJ x86"));
  s = p6;
  s[15] = 2;
  CHECK(error_has(fix_block_header(s), "LZMA2 properties must be one byte"));
  s = p6;
  s[18] = 1;
  CHECK(error_has(fix_block_header(s), "non-zero padding"));
  s = p6;
  s[12] = 0x7F;  // header size 512: runs into the data, CRC mismatch
  CHECK(throws_xz(s));
  // LZMA2 control and properties bytes of the first chunk.
  s = p6;
  s[24] = 0x03;
  CHECK(error_has(s, "invalid control byte"));
  s[24] = static_cast<char>(0x80 | (p6[24] & 0x1F));
  CHECK(error_has(s, "no dictionary reset"));
  s[24] = static_cast<char>(0xC0 | (p6[24] & 0x1F));
  CHECK(error_has(s, "no dictionary reset"));
  s[24] = 0x02;
  CHECK(error_has(s, "no dictionary reset"));
  s = p6;
  s[29] = static_cast<char>(225);
  CHECK(error_has(s, "invalid properties byte"));
  s[29] = (0 * 5 + 1) * 9 + 4;  // lc 4 + lp 1
  CHECK(error_has(s, "lc + lp > 4"));
  s = p6;
  s[30] = 1;  // the range coder's first byte must be 0
  CHECK(error_has(s, "range coder"));
  // The integrity check (just before the index), the index and the stream footer.
  s = p6;
  s[index_start(s) - 1] ^= 1;
  CHECK(error_has(s, "integrity check mismatch"));
  s = p6;
  s[index_start(s) + 1] = 2;  // the record count (checked as soon as it is read)
  CHECK(error_has(s, "index lists 2 blocks, the stream has 1"));
  s = p6;
  s[index_start(s) + 3] ^= 2;  // the record's unpadded size (two bytes) grows by 256
  CHECK(error_has(s, "index CRC32") || error_has(s, "index does not match"));
  CHECK(error_has(fix_index(s), "index does not match"));
  s = p6;
  s[s.size() - 13] ^= 1;  // the index CRC32
  CHECK(error_has(s, "index CRC32 mismatch"));
  s = p6;
  s[s.size() - 8] ^= 1;
  CHECK(error_has(s, "footer CRC32"));
  CHECK(error_has(fix_footer(s), "backward size"));
  s = p6;
  s[s.size() - 3] = 1;
  CHECK(error_has(fix_footer(s), "footer flags differ"));
  s = p6;
  s[s.size() - 1] = 'X';
  CHECK(error_has(s, "footer magic"));
  // Sizes in a block header (multi-block file): compressed size, uncompressed size.
  const std::string mb = data_file("xz_multiblock.xz");
  size_t p = 14;
  while (static_cast<unsigned char>(mb[p]) & 0x80) ++p;
  const size_t usize_at = p + 1;
  s = mb;
  s[14] ^= 1;
  CHECK(error_has(fix_block_header(s), "compressed size mismatch"));
  s = mb;
  s[usize_at] ^= 1;
  CHECK(error_has(fix_block_header(s), "uncompressed size mismatch"));
}

TEST(xz_corrupt_flips) {
  // Every single-bit change of a checked file is either detected (a header CRC, a structural
  // check, the range coder's end condition or the integrity check) or harmless: a different lc in
  // an LZMA properties byte can be an equally valid encoding of the same text when the literal
  // contexts that occur map one to one (only lower-case letters, say), and then the output is
  // still exactly right. Any other output would be a miss.
  const std::string st = small_text();
  std::vector<std::pair<std::string, std::string>> checked;
  for (const std::string& v : small_text_vectors()) checked.emplace_back(v, st);
  checked.erase(checked.begin() + 4);  // k_check_none: changed data can decode without error
  checked.emplace_back(bytes(k_streams), "first stream\nsecond stream\n");
  checked.emplace_back(bytes(k_sha_lengths), sha_lengths_text());
  checked.emplace_back(bytes(k_spliced), spliced_text());
  checked.emplace_back(bytes(k_noise), noise(300, 7));
  int flips = 0, accepted = 0, wrong = 0;
  for (const auto& [v, want] : checked) {
    for (size_t i = 0; i < v.size(); ++i) {
      for (int mask : {0x01, 0x10, 0x80}) {
        std::string b = v;
        b[i] = static_cast<char>(b[i] ^ mask);
        ++flips;
        try {
          const std::string out = unxz_str(b);
          ++accepted;
          if (out != want) {
            ++wrong;
            std::fprintf(stderr, "  wrong output after a flip at %zu (mask %d) of a %zu-byte vector\n", i, mask,
                         v.size());
          }
        } catch (const XzError&) {
        }
      }
    }
  }
  CHECK(wrong == 0);
  CHECK(accepted * 200 < flips);  // nearly all changes are detected outright
  // Without a check, changed data must still never crash (it decodes or throws).
  const std::string none = bytes(k_check_none);
  for (size_t i = 0; i < none.size(); ++i) {
    std::string b = none;
    b[i] = static_cast<char>(b[i] ^ 0x10);
    (void)xz_error(b);
  }
  // Spread over the large file.
  const std::string big = data_file("xz_big_p6.xz");
  int big_missed = 0;
  for (size_t i = 0; i < big.size(); i += 4999) {
    std::string b = big;
    b[i] = static_cast<char>(b[i] ^ 0x04);
    big_missed += !throws_xz(b);
  }
  CHECK(big_missed == 0);
}

TEST(xz_truncated) {
  std::vector<std::string> single = small_text_vectors();
  single.push_back(bytes(k_spliced));
  single.push_back(bytes(k_noise));
  single.push_back(bytes(k_empty));
  bool all = true;
  for (const std::string& v : single) {
    for (size_t n = 0; n < v.size(); ++n) all = all && throws_xz(v.substr(0, n));
    for (size_t n = 1; n < v.size(); n += 5) all = all && throws_xz(v.substr(0, n), 7);
  }
  CHECK(all);
  // A file of several streams is valid when cut at a stream boundary (and padding may be cut in
  // groups of four); anywhere else it is an error.
  const std::string ms = bytes(k_streams);
  bool prefixes_ok = true;
  for (size_t n = 1; n < ms.size(); ++n) {
    try {
      const std::string out = unxz_str(ms.substr(0, n));
      prefixes_ok = prefixes_ok && (out == "first stream\n" || out == "first stream\nsecond stream\n");
    } catch (const XzError&) {
    }
  }
  CHECK(prefixes_ok);
  const std::string big = data_file("xz_big_p6.xz");
  bool big_all = true;
  for (size_t n = 0; n < big.size(); n += big.size() / 16) big_all = big_all && throws_xz(big.substr(0, n));
  for (size_t k : {1, 2, 3, 4, 5, 8, 12, 13, 20, 33}) {
    big_all = big_all && throws_xz(big.substr(0, big.size() - k), 4096);
  }
  CHECK(big_all);
}

TEST(xz_sink_exception_propagates) {
  // An exception from the sink (e.g. a parse error in the consumer) passes through unchanged.
  const std::string mb = data_file("xz_multiblock.xz");
  size_t pos = 0, calls = 0;
  bool caught = false;
  try {
    unxz(
        [&](unsigned char* buf, size_t cap) {
          const size_t n = std::min(cap, mb.size() - pos);
          std::copy(mb.data() + pos, mb.data() + pos + n, buf);
          pos += n;
          return n;
        },
        [&](const char*, size_t) {
          ++calls;
          throw std::runtime_error("consumer stops");
        });
  } catch (const XzError&) {
  } catch (const std::runtime_error& e) {
    caught = std::string(e.what()) == "consumer stops";
  }
  CHECK(caught);
  CHECK(calls == 1);
}
